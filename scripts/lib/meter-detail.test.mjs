import { mkdtemp, mkdir, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { describe, expect, it } from "vitest";
import {
  METER_DETAIL_BANNER,
  checkMeterDetailFile,
  compareUnportableMenuCard,
  menuCardReviewProblems,
  menuCardWatchDigest,
  MENU_CARD_WATCH_PATHS,
  meterEntryFromPresentation,
  parseMenuCardPresentation,
  readMenuCardWatchFiles,
  renderMeterDetail,
} from "./meter-detail.mjs";

const EMPTY = {
  showsPrimaryBalanceDescription: false,
  showsSecondaryBalanceDescription: false,
  hidesPrimaryResetWithoutDate: false,
  clearsPrimaryReset: false,
  usesRawPrimaryResetDescription: false,
  movePrimaryDetailToStatus: false,
  movePrimaryDetailToStatusClosure: null,
  primaryDescriptionPlacement: "standard",
  primaryDetailKind: "none",
  usageNotesResolver: null,
  blockingQuota: null,
  resetWindowUsesWeeklyPace: null,
  extraRateWindowUsesResetDescriptionAsDetail: null,
  extraResetDescriptionAsDetail: null,
  primaryDescriptionIsDetail: null,
  unknownArguments: {},
};

function watchedTree(overrides = {}) {
  const files = {
    "Sources/CodexBar/MenuCardView.swift": "struct MenuCard {}\n",
    "Sources/CodexBar/MenuCardView+ModelHelpers.swift": "extension MenuCard {}\n",
    "Sources/CodexBar/MenuCardMetricRow.swift": "struct MetricRow {}\n",
    "Sources/CodexBarCLI/CLIRenderer.swift": "enum CLIRenderer {}\n",
    "Sources/CodexBarCore/Resources/Plugins/raycast.js": "export const raycast = 1;\n",
    "Sources/CodexBarCore/Resources/Plugins/zed.js": "export const zed = 1;\n",
    "README.md": "not watched\n",
    ...overrides,
  };
  return {
    label: "fixture tree",
    listFiles: async (prefix, suffix) =>
      Object.keys(files).filter((file) => file.startsWith(prefix) && file.endsWith(suffix)),
    readFile: async (file) => {
      if (!(file in files)) throw new Error(`missing ${file}`);
      return files[file];
    },
  };
}

async function watchedDigest(overrides) {
  return menuCardWatchDigest(await readMenuCardWatchFiles(watchedTree(overrides)));
}

describe("meter detail generation", () => {
  it("keeps the do-not-edit banner on every generated table", () => {
    const lines = METER_DETAIL_BANNER.split("\n");
    expect(lines[0]).toMatch(/^\/\/ \*+$/);
    expect(lines[1]).toBe("// Generated by scripts/lib/meter-detail.mjs. Don't hand-edit.");
    expect(lines[2]).toBe(
      "// Run npm run upstream:sync-meter-detail to rewrite it. upstream:check rejects a hand edit.",
    );
    expect(lines[3]).toBe(lines[0]);
    expect(lines[4]).toBe("");
    expect(lines[0].length).toBeGreaterThanOrEqual(lines[2].length);
    expect(renderMeterDetail({}).startsWith(METER_DETAIL_BANNER)).toBe(true);
  });

  it("ignores comments inside a menu card call", () => {
    const source = `
      ProviderMenuCardPresentation(
        supportsInlineTokenCostDashboard: true,
        // Antigravity has no single account-wide weekly quota: it reports a weekly bucket
        // per model family, and \`semanticWindows\` surfaces whichever family is most
        // constrained, while the cost bucketed into it spans every model.
        showsPrimaryBalanceDescription: false)
    `;
    const parsed = parseMenuCardPresentation(source, "Antigravity.swift");
    expect(parsed.ok).toBe(true);
    if (!parsed.ok) return;
    expect(parsed.presentation.showsPrimaryBalanceDescription).toBe(false);
    expect(meterEntryFromPresentation("antigravity", parsed.presentation)).toBeUndefined();
  });

  it("rejects two menu card calls and treats zero calls as defaults", () => {
    const none = parseMenuCardPresentation("struct Empty {}", "Empty.swift");
    expect(none.ok).toBe(true);
    const doubled = parseMenuCardPresentation(
      "ProviderMenuCardPresentation()\nProviderMenuCardPresentation()",
      "Double.swift",
    );
    expect(doubled.ok).toBe(false);
    if (doubled.ok) return;
    expect(doubled.error).toMatch(/2 ProviderMenuCardPresentation calls/);
  });

  it("maps placements, balance flags, detail kinds, and the forced menu-card rows", () => {
    expect(meterEntryFromPresentation("devin", EMPTY)).toBeUndefined();
    expect(meterEntryFromPresentation("warp", EMPTY)).toEqual({ secondaryDetailText: true });
    expect(meterEntryFromPresentation("alibaba", EMPTY)).toEqual({
      secondaryDetailText: true,
      tertiaryDetailText: true,
    });
    expect(meterEntryFromPresentation("alibabatokenplan", EMPTY)).toEqual({
      secondaryDetailText: true,
      tertiaryDetailText: true,
    });
    expect(meterEntryFromPresentation("plain", { ...EMPTY, primaryDescriptionPlacement: "standard" })).toBeUndefined();
    expect(meterEntryFromPresentation("copilot", { ...EMPTY, primaryDescriptionPlacement: "detailLeft" })).toEqual({
      primaryDescriptionPlacement: "detailLeft",
      secondaryReplacesPace: "resetDescription",
    });
    expect(meterEntryFromPresentation("zenmux", { ...EMPTY, primaryDescriptionPlacement: "detail" })).toEqual({
      primaryDescriptionPlacement: "detail",
      secondaryReplacesPace: "resetDescription",
      secondaryHidesResetWithoutDate: true,
    });
    expect(meterEntryFromPresentation("openrouter", { ...EMPTY, primaryDescriptionPlacement: "reset" })).toEqual({
      primaryDescriptionPlacement: "reset",
    });
    expect(meterEntryFromPresentation("kiro", { ...EMPTY, primaryDetailKind: "kiroCredits" })).toEqual({
      primaryDetailKind: "kiroCredits",
      secondaryReplacesPace: "kiroBonusCredits",
      extraDetailLeft: "kiroOverage",
    });
    expect(meterEntryFromPresentation("poe", { ...EMPTY, primaryDetailKind: "poeBalance" })).toEqual({
      primaryDetailKind: "poeBalance",
    });
    expect(meterEntryFromPresentation("cursor", { ...EMPTY, primaryDetailKind: "requestQuota" })).toBeUndefined();
    expect(
      meterEntryFromPresentation("raycast", {
        ...EMPTY,
        showsPrimaryBalanceDescription: true,
        hidesPrimaryResetWithoutDate: true,
      }),
    ).toEqual({
      showsPrimaryBalanceDescription: true,
      hidesPrimaryResetWithoutDate: true,
    });
    expect(
      meterEntryFromPresentation("manus", {
        ...EMPTY,
        showsSecondaryBalanceDescription: true,
        clearsPrimaryReset: true,
      }),
    ).toEqual({
      showsSecondaryBalanceDescription: true,
      clearsPrimaryReset: true,
    });
    expect(meterEntryFromPresentation("sub2api", { ...EMPTY, extraResetDescriptionAsDetail: true })).toEqual({
      secondaryRawResetDescription: true,
      tertiaryRawResetDescription: true,
      extraResetDescriptionAsDetail: true,
    });
    expect(
      meterEntryFromPresentation("mistral", { ...EMPTY, extraResetDescriptionAsDetail: "mistral-monthly-plan" }),
    ).toEqual({ extraResetDescriptionAsDetail: "mistral-monthly-plan" });
  });

  it("ports a true extra-window closure and an id check, and leaves any other body unportable", () => {
    const all = parseMenuCardPresentation(
      "ProviderMenuCardPresentation(extraRateWindowUsesResetDescriptionAsDetail: { _ in true })",
      "Sub2API.swift",
    );
    expect(all.ok).toBe(true);
    if (!all.ok) return;
    expect(all.presentation.extraResetDescriptionAsDetail).toBe(true);
    expect(all.presentation.extraRateWindowUsesResetDescriptionAsDetail).toBeNull();

    const id = parseMenuCardPresentation(
      'ProviderMenuCardPresentation(extraRateWindowUsesResetDescriptionAsDetail: { $0.id == "mistral-monthly-plan" })',
      "Mistral.swift",
    );
    expect(id.ok).toBe(true);
    if (!id.ok) return;
    expect(id.presentation.extraResetDescriptionAsDetail).toBe("mistral-monthly-plan");
    expect(id.presentation.extraRateWindowUsesResetDescriptionAsDetail).toBeNull();

    const other = parseMenuCardPresentation(
      'ProviderMenuCardPresentation(extraRateWindowUsesResetDescriptionAsDetail: { name in name.id.hasPrefix("x") })',
      "Other.swift",
    );
    expect(other.ok).toBe(true);
    if (!other.ok) return;
    expect(other.presentation.extraResetDescriptionAsDetail).toBeNull();
    expect(other.presentation.extraRateWindowUsesResetDescriptionAsDetail).toContain("hasPrefix");
  });

  it("rejects a hand edit and accepts the regenerated file", async () => {
    const root = await mkdtemp(path.join(os.tmpdir(), "meter-detail-"));
    const entries = { raycast: { showsPrimaryBalanceDescription: true } };
    const file = path.join(root, "src/providers/meterDetail.ts");
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(
      file,
      renderMeterDetail(entries).replace(
        "showsPrimaryBalanceDescription: true",
        "showsPrimaryBalanceDescription: true /* edited */",
      ),
    );
    await expect(checkMeterDetailFile(root, entries)).resolves.toEqual([
      "src/providers/meterDetail.ts does not match the menu card descriptors. Run npm run upstream:sync-meter-detail.",
    ]);
    await writeFile(file, renderMeterDetail(entries));
    await expect(checkMeterDetailFile(root, entries)).resolves.toEqual([]);
    await rm(root, { recursive: true, force: true });
  });

  it("ports usesRawPrimaryResetDescription and an always-true movePrimaryDetailToStatus", () => {
    const sub2api = parseMenuCardPresentation(
      "ProviderMenuCardPresentation(extraRateWindowUsesResetDescriptionAsDetail: { _ in true }, usesRawPrimaryResetDescription: true)",
      "Sub2API.swift",
    );
    expect(sub2api.ok).toBe(true);
    if (!sub2api.ok) return;
    expect(meterEntryFromPresentation("sub2api", sub2api.presentation)).toEqual({
      usesRawPrimaryResetDescription: true,
      secondaryRawResetDescription: true,
      tertiaryRawResetDescription: true,
      extraResetDescriptionAsDetail: true,
    });

    const deepseek = parseMenuCardPresentation(
      "ProviderMenuCardPresentation(showsPrimaryBalanceDescription: true, movePrimaryDetailToStatus: { _ in true })",
      "DeepSeek.swift",
    );
    expect(deepseek.ok).toBe(true);
    if (!deepseek.ok) return;
    expect(meterEntryFromPresentation("deepseek", deepseek.presentation)).toEqual({
      showsPrimaryBalanceDescription: true,
      movePrimaryDetailToStatus: true,
    });
    expect(compareUnportableMenuCard(new Map([["deepseek", deepseek.presentation]]), {})).toEqual([]);

    const closure = parseMenuCardPresentation(
      "ProviderMenuCardPresentation(movePrimaryDetailToStatus: { $0?.primary == nil })",
      "Other.swift",
    );
    expect(closure.ok).toBe(true);
    if (!closure.ok) return;
    expect(meterEntryFromPresentation("other", closure.presentation)).toBeUndefined();
    expect(compareUnportableMenuCard(new Map([["other", closure.presentation]]), {})).toEqual([
      "other: descriptor sets movePrimaryDetailToStatus. Port it or add UNPORTABLE_MENU_CARD.",
    ]);
  });

  it("names the perplexity and sub2api reset-description branches", () => {
    expect(meterEntryFromPresentation("perplexity", EMPTY)).toEqual({
      secondaryResetDescriptionAsReset: true,
      tertiaryRawResetDescription: true,
    });
  });

  it("renders the new flags into the generated table and type", () => {
    const rendered = renderMeterDetail({
      sub2api: { usesRawPrimaryResetDescription: true, secondaryRawResetDescription: true },
      deepseek: { movePrimaryDetailToStatus: true },
      perplexity: { secondaryResetDescriptionAsReset: true, tertiaryRawResetDescription: true },
    });
    expect(rendered).toContain("  usesRawPrimaryResetDescription?: true;");
    expect(rendered).toContain("  movePrimaryDetailToStatus?: true;");
    expect(rendered).toContain("  secondaryRawResetDescription?: true;");
    expect(rendered).toContain("  secondaryResetDescriptionAsReset?: true;");
    expect(rendered).toContain("  tertiaryRawResetDescription?: true;");
    expect(rendered).toContain(
      "  sub2api: { usesRawPrimaryResetDescription: true, secondaryRawResetDescription: true },",
    );
    expect(rendered).toContain("  deepseek: { movePrimaryDetailToStatus: true },");
    expect(rendered).toContain(
      "  perplexity: { secondaryResetDescriptionAsReset: true, tertiaryRawResetDescription: true },",
    );
    for (const runtimeOnly of ["statusText", "detailRightText", "showPaceMarker", "replacesPace"]) {
      expect(rendered).not.toMatch(new RegExp(`^  ${runtimeOnly}\\?:`, "m"));
    }
  });

  it("fails an unknown menu card argument until UNPORTABLE_MENU_CARD names it", () => {
    const parsed = parseMenuCardPresentation(
      "ProviderMenuCardPresentation(showsPrimaryBalanceDescription: true, invents: .something)",
      "Toy.swift",
    );
    expect(parsed.ok).toBe(true);
    if (!parsed.ok) return;
    const presentations = new Map([["toy", parsed.presentation]]);
    expect(compareUnportableMenuCard(presentations, {})).toEqual([
      "toy: descriptor sets invents, a menu card argument meter-detail.mjs does not know. Port it or add UNPORTABLE_MENU_CARD.",
    ]);
    expect(compareUnportableMenuCard(presentations, { toy: { invents: "not a meter row" } })).toEqual([]);

    const menu = parseMenuCardPresentation(
      "ProviderMenuDescriptorPresentation(primaryDescriptionIsDetail: { _ in false }, futureFlag: true)",
      "Toy.swift",
    );
    expect(menu.ok).toBe(true);
    if (!menu.ok) return;
    expect(compareUnportableMenuCard(new Map([["toy", menu.presentation]]), {}).join("\n")).toContain("futureFlag");
  });

  it("knows every argument the descriptors pass at the pinned sha without an allowlist", () => {
    const parsed = parseMenuCardPresentation(
      `ProviderMenuCardPresentation(
        creditsVisibility: .hiddenWhenUsageSnapshotPresent,
        showsCreditsSection: false,
        costVisibilityResolver: { $0.showOptionalUsage },
        providerCostIsRequiredUsage: true,
        usesProviderCostHistoryAsPrimaryDashboard: true,
        primaryCostHistoryResolver: { _, tokenSnapshot in tokenSnapshot },
        supportsInlineTokenCostDashboard: true,
        showsQuotaWeekCost: true,
        quotaWindowNote: "note",
        ignoresObservedQuotaResetBoundaries: true,
        usesAbacusPace: true,
        usesSyntheticRollingRegen: true)
      ProviderMenuDescriptorPresentation(
        showsPrimaryWeeklyPace: true,
        secondaryDescriptionMode: .resetOverride,
        tertiaryDescriptionOverridesReset: true)`,
      "Toy.swift",
    );
    expect(parsed.ok).toBe(true);
    if (!parsed.ok) return;
    expect(parsed.presentation.unknownArguments).toEqual({});
    expect(compareUnportableMenuCard(new Map([["toy", parsed.presentation]]), {})).toEqual([]);
  });

  it("requires UNPORTABLE_MENU_CARD for Kimi blockingQuota and resetWindowUsesWeeklyPace, and still rejects a stale entry", () => {
    const parsed = parseMenuCardPresentation(
      'ProviderMenuCardPresentation(resetWindowUsesWeeklyPace: true, blockingQuota: ("kimi-monthly", "Blocked by monthly limit"))',
      "Kimi.swift",
    );
    expect(parsed.ok).toBe(true);
    if (!parsed.ok) return;
    const presentations = new Map([["kimi", parsed.presentation]]);
    expect(compareUnportableMenuCard(presentations, {})).toEqual([
      "kimi: descriptor sets blockingQuota. Port it or add UNPORTABLE_MENU_CARD.",
      "kimi: descriptor sets resetWindowUsesWeeklyPace. Port it or add UNPORTABLE_MENU_CARD.",
    ]);
    const allowed = { kimi: { blockingQuota: "binding projection", resetWindowUsesWeeklyPace: "pace" } };
    expect(compareUnportableMenuCard(presentations, allowed)).toEqual([]);

    const plain = parseMenuCardPresentation("ProviderMenuCardPresentation(blockingQuota: nil)", "Kimi.swift");
    expect(plain.ok).toBe(true);
    if (!plain.ok) return;
    expect(compareUnportableMenuCard(new Map([["kimi", plain.presentation]]), allowed)).toEqual([
      "kimi: stale UNPORTABLE_MENU_CARD entry for blockingQuota. Delete it.",
      "kimi: stale UNPORTABLE_MENU_CARD entry for resetWindowUsesWeeklyPace. Delete it.",
    ]);
  });

  it("digests the watch list and every watched file in a stable order", async () => {
    const base = await watchedDigest();
    expect(base).toMatch(/^[0-9a-f]{64}$/);
    expect(await watchedDigest()).toBe(base);
    expect(await watchedDigest({ "README.md": "changed\n" })).toBe(base);
    expect(
      await watchedDigest({ "Sources/CodexBarCore/Resources/Plugins/zed.js": "export const zed = 2;\n" }),
    ).not.toBe(base);
    expect(await watchedDigest({ "Sources/CodexBarCore/Resources/Plugins/new.js": "" })).not.toBe(base);
    const files = await readMenuCardWatchFiles(watchedTree());
    expect(files.map((file) => file.path)).toEqual([
      "Sources/CodexBar/MenuCardView.swift",
      "Sources/CodexBar/MenuCardView+ModelHelpers.swift",
      "Sources/CodexBar/MenuCardMetricRow.swift",
      "Sources/CodexBarCLI/CLIRenderer.swift",
      "Sources/CodexBarCore/Resources/Plugins/raycast.js",
      "Sources/CodexBarCore/Resources/Plugins/zed.js",
    ]);
    await expect(readMenuCardWatchFiles({ ...watchedTree(), listFiles: async () => [] })).rejects.toThrow(
      /has no files/,
    );
  });

  it("passes when the watched bytes match the digest, even with sha left behind", async () => {
    const digest = await watchedDigest();
    const reviewed = { sha: "a".repeat(40), digest, paths: [...MENU_CARD_WATCH_PATHS] };
    expect(menuCardReviewProblems(reviewed, { sha: "b".repeat(40), digest }, ["README.md"])).toEqual([]);
    expect(menuCardReviewProblems(reviewed, { sha: "b".repeat(40), digest }, [])).toEqual([]);
  });

  it("fails a digest mismatch, a sha-only update, and a path-only update", async () => {
    const before = await watchedDigest();
    const plugin = "Sources/CodexBarCore/Resources/Plugins/raycast.js";
    const after = await watchedDigest({ [plugin]: "export const raycast = 2;\n" });
    const candidate = { sha: "b".repeat(40), digest: after };
    const changed = [plugin, "README.md"];

    const stale = menuCardReviewProblems(
      { sha: "a".repeat(40), digest: before, paths: [...MENU_CARD_WATCH_PATHS] },
      candidate,
      changed,
    );
    const staleText = stale.join("\n");
    expect(staleText).toContain("raycast.js");
    expect(staleText).toContain(candidate.sha);
    expect(staleText).toContain(`menuCardReviewed.digest to ${after}`);
    expect(staleText).toContain("menuCardReviewed.paths");
    expect(staleText).not.toContain("README.md");
    expect(staleText).not.toContain("meterDetail.ts by hand");

    const shaOnly = menuCardReviewProblems(
      { sha: candidate.sha, digest: before, paths: [...MENU_CARD_WATCH_PATHS] },
      candidate,
      changed,
    );
    expect(shaOnly.join("\n")).toContain("menuCardReviewed.digest");

    const pathOnly = menuCardReviewProblems(
      { sha: "a".repeat(40), digest: before, paths: [...MENU_CARD_WATCH_PATHS, plugin] },
      candidate,
      changed,
    );
    expect(pathOnly.join("\n")).toContain("menuCardReviewed.digest");

    const shaAndPath = menuCardReviewProblems(
      { sha: candidate.sha, digest: before, paths: [...MENU_CARD_WATCH_PATHS, plugin] },
      candidate,
      [],
    );
    expect(shaAndPath.join("\n")).toContain("do not match menuCardReviewed.digest");

    const digestWithoutPath = menuCardReviewProblems(
      { sha: candidate.sha, digest: after, paths: [...MENU_CARD_WATCH_PATHS] },
      candidate,
      changed,
    );
    expect(digestWithoutPath).toEqual([`menuCardReviewed.paths does not list changed file ${plugin}.`]);

    const digestWithoutSha = menuCardReviewProblems(
      { sha: "a".repeat(40), digest: after, paths: [...MENU_CARD_WATCH_PATHS, plugin] },
      candidate,
      changed,
    );
    expect(digestWithoutSha.join("\n")).toContain(`Set menuCardReviewed.sha to ${candidate.sha}`);

    expect(
      menuCardReviewProblems(
        { sha: candidate.sha, digest: after, paths: [...MENU_CARD_WATCH_PATHS, plugin] },
        candidate,
        changed,
      ),
    ).toEqual([]);
  });

  it("rejects a listed path outside the watch list", async () => {
    const digest = await watchedDigest();
    const problems = menuCardReviewProblems(
      {
        sha: "a".repeat(40),
        digest,
        paths: [...MENU_CARD_WATCH_PATHS, "README.md", "Sources/CodexBarCore/Resources/Plugins/zed.js"],
      },
      { sha: "a".repeat(40), digest },
      [],
    );
    expect(problems).toEqual(["menuCardReviewed lists README.md, which is not a watched menu card path. Delete it."]);
    expect(
      menuCardReviewProblems(
        { sha: "a".repeat(40), digest, paths: MENU_CARD_WATCH_PATHS.slice(1) },
        { sha: "a".repeat(40), digest },
        [],
      ),
    ).toEqual([`menuCardReviewed is missing watched path ${MENU_CARD_WATCH_PATHS[0]}.`]);
  });
});
