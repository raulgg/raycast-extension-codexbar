export function parseMenuCardPresentation(source, filePath = "descriptor") {
  try {
    const cardCalls = findCalls(source, "ProviderMenuCardPresentation");
    const menuCalls = findCalls(source, "ProviderMenuDescriptorPresentation");
    if (cardCalls.length > 1) {
      throw new Error(`${cardCalls.length} ProviderMenuCardPresentation calls`);
    }
    if (menuCalls.length > 1) {
      throw new Error(`${menuCalls.length} ProviderMenuDescriptorPresentation calls`);
    }
    const card = cardCalls.length === 0 ? new Map() : parseArgs(cardCalls[0]);
    const menu = menuCalls.length === 0 ? new Map() : parseArgs(menuCalls[0]);
    const unknownArguments = {
      ...unknownArgs(card, MENU_CARD_ARGUMENTS),
      ...unknownArgs(menu, MENU_DESCRIPTOR_ARGUMENTS),
    };
    const extraReset = classifyExtraResetDetail(card.get("extraRateWindowUsesResetDescriptionAsDetail"));
    const moveToStatus = classifyAlwaysClosure(card, "movePrimaryDetailToStatus");
    return {
      ok: true,
      presentation: {
        showsPrimaryBalanceDescription: boolArg(card, "showsPrimaryBalanceDescription", false),
        showsSecondaryBalanceDescription: boolArg(card, "showsSecondaryBalanceDescription", false),
        hidesPrimaryResetWithoutDate: boolArg(card, "hidesPrimaryResetWithoutDate", false),
        clearsPrimaryReset: boolArg(card, "clearsPrimaryReset", false),
        usesRawPrimaryResetDescription: boolArg(card, "usesRawPrimaryResetDescription", false),
        movePrimaryDetailToStatus: moveToStatus.ported,
        movePrimaryDetailToStatusClosure: moveToStatus.unportable,
        primaryDescriptionPlacement: enumArg(card, "primaryDescriptionPlacement", "standard", PLACEMENTS),
        primaryDetailKind: enumArg(card, "primaryDetailKind", "none", DETAIL_KINDS),
        usageNotesResolver: closureArg(card, "usageNotesResolver", TRIVIAL_UNHANDLED),
        blockingQuota: rawArg(card, "blockingQuota", TRIVIAL_NIL),
        resetWindowUsesWeeklyPace: rawArg(card, "resetWindowUsesWeeklyPace", "false"),
        extraRateWindowUsesResetDescriptionAsDetail: extraReset.unportable,
        extraResetDescriptionAsDetail: extraReset.ported,
        primaryDescriptionIsDetail: closureArg(menu, "primaryDescriptionIsDetail", TRIVIAL_FALSE),
        unknownArguments,
      },
    };
  } catch (error) {
    return { ok: false, error: `${filePath}: ${error instanceof Error ? error.message : error}` };
  }
}

export function meterEntryFromPresentation(id, presentation) {
  const entry = {};
  const placement = presentation.primaryDescriptionPlacement;
  const kind = presentation.primaryDetailKind;
  if (placement && placement !== "standard") {
    entry.primaryDescriptionPlacement = placement;
  }
  if (presentation.showsPrimaryBalanceDescription) {
    entry.showsPrimaryBalanceDescription = true;
  }
  if (presentation.showsSecondaryBalanceDescription) {
    entry.showsSecondaryBalanceDescription = true;
  }
  if (presentation.hidesPrimaryResetWithoutDate) {
    entry.hidesPrimaryResetWithoutDate = true;
  }
  if (presentation.clearsPrimaryReset) {
    entry.clearsPrimaryReset = true;
  }
  if (presentation.usesRawPrimaryResetDescription) {
    entry.usesRawPrimaryResetDescription = true;
  }
  if (kind === "kiroCredits" || kind === "poeBalance") {
    entry.primaryDetailKind = kind;
  }
  if (presentation.movePrimaryDetailToStatus) {
    entry.movePrimaryDetailToStatus = true;
  }
  if (SECONDARY_DETAIL_TEXT.has(id)) {
    entry.secondaryDetailText = true;
  }
  if (SECONDARY_RESET_DESCRIPTION_PACE.has(id)) {
    entry.secondaryReplacesPace = "resetDescription";
  }
  if (SECONDARY_KIRO_BONUS_PACE.has(id)) {
    entry.secondaryReplacesPace = "kiroBonusCredits";
  }
  if (SECONDARY_HIDES_RESET_WITHOUT_DATE.has(id)) {
    entry.secondaryHidesResetWithoutDate = true;
  }
  if (SECONDARY_RAW_RESET_DESCRIPTION.has(id)) {
    entry.secondaryRawResetDescription = true;
  }
  if (SECONDARY_RESET_DESCRIPTION_AS_RESET.has(id)) {
    entry.secondaryResetDescriptionAsReset = true;
  }
  if (TERTIARY_DETAIL_TEXT.has(id)) {
    entry.tertiaryDetailText = true;
  }
  if (TERTIARY_RAW_RESET_DESCRIPTION.has(id)) {
    entry.tertiaryRawResetDescription = true;
  }
  if (presentation.extraResetDescriptionAsDetail) {
    entry.extraResetDescriptionAsDetail = presentation.extraResetDescriptionAsDetail;
  }
  if (EXTRA_KIRO_OVERAGE.has(id)) {
    entry.extraDetailLeft = "kiroOverage";
  }
  return Object.keys(entry).length === 0 ? undefined : entry;
}

export function compareMeterDetail(presentations, table) {
  const problems = [];
  const entries = {};
  for (const [id, presentation] of presentations) {
    const expected = meterEntryFromPresentation(id, presentation);
    if (expected) entries[id] = expected;
    const actual = table[id];
    if (!sameEntry(expected, actual)) {
      problems.push(
        `${id}: meterDetail.ts has ${describeEntry(actual)} but the menu card needs ${describeEntry(expected)}. Run ${SYNC_METER_DETAIL_COMMAND}.`,
      );
    }
  }
  for (const id of Object.keys(table)) {
    if (!presentations.has(id)) {
      problems.push(`${id}: meterDetail.ts lists a Provider with no descriptor. Run ${SYNC_METER_DETAIL_COMMAND}.`);
    }
  }
  return { problems, entries };
}

export function compareUnportableMenuCard(presentations, allowances) {
  const problems = [];
  const used = new Set();
  for (const [id, presentation] of presentations) {
    const allowance = allowances[id] ?? {};
    if (presentation.primaryDetailKind === "requestQuota") {
      if (!allowance.requestQuota) {
        problems.push(
          `${id}: descriptor sets primaryDetailKind .requestQuota. Port it or add UNPORTABLE_MENU_CARD.`,
        );
      } else {
        used.add(`${id}.requestQuota`);
      }
    }
    for (const field of UNPORTABLE_FIELDS) {
      if (!presentation[field]) continue;
      // An unported movePrimaryDetailToStatus closure is still that argument to a reader of the lists.
      const key = field === "movePrimaryDetailToStatusClosure" ? "movePrimaryDetailToStatus" : field;
      if (!allowance[key]) {
        problems.push(`${id}: descriptor sets ${key}. Port it or add UNPORTABLE_MENU_CARD.`);
      } else {
        used.add(`${id}.${key}`);
      }
    }
    for (const name of Object.keys(presentation.unknownArguments ?? {})) {
      if (!allowance[name]) {
        problems.push(
          `${id}: descriptor sets ${name}, a menu card argument meter-detail.mjs does not know. Port it or add UNPORTABLE_MENU_CARD.`,
        );
      } else {
        used.add(`${id}.${name}`);
      }
    }
    for (const key of Object.keys(allowance)) {
      if (!used.has(`${id}.${key}`)) {
        problems.push(`${id}: stale UNPORTABLE_MENU_CARD entry for ${key}. Delete it.`);
      }
    }
  }
  for (const [id, flags] of Object.entries(allowances)) {
    if (presentations.has(id)) continue;
    for (const key of Object.keys(flags)) {
      problems.push(`${id}: stale UNPORTABLE_MENU_CARD entry for ${key}. Delete it.`);
    }
  }
  return problems;
}

export function isWatchedMenuCardPath(file) {
  return MENU_CARD_WATCH_PATHS.some((watch) => (watch.endsWith("/") ? file.startsWith(watch) : file === watch));
}

export function watchedMenuCardChanges(changedPaths) {
  return [...new Set(changedPaths.filter(isWatchedMenuCardPath))].sort();
}

// Reads every watched file at the source's ref. A directory entry expands to the files under it.
export async function readMenuCardWatchFiles(source) {
  const files = [];
  for (const watch of MENU_CARD_WATCH_PATHS) {
    const paths = watch.endsWith("/")
      ? (await source.listFiles(watch, "")).filter((file) => file.startsWith(watch)).sort(compareCodePoints)
      : [watch];
    if (paths.length === 0) {
      throw new Error(`Watched menu card directory ${watch} has no files in ${source.label}.`);
    }
    for (const file of paths) {
      files.push({ watch, path: file, content: await source.readFile(file) });
    }
  }
  return files;
}

// sha256 over the watch list and the watched file contents, in watch-list order and then path order.
// Each record carries its length, so moving bytes between files changes the digest.
export function menuCardWatchDigest(files) {
  const hash = createHash("sha256");
  const record = (tag, value) => {
    const bytes = Buffer.from(value, "utf8");
    hash.update(`${tag} ${bytes.length}\n`);
    hash.update(bytes);
    hash.update("\n");
  };
  for (const watch of MENU_CARD_WATCH_PATHS) {
    record("watch", watch);
    for (const file of files.filter((entry) => entry.watch === watch)) {
      record("path", file.path);
      record("content", file.content);
    }
  }
  return hash.digest("hex");
}

// candidate: { sha, digest } of the upstream ref being checked.
// changedPaths: files that differ between the pinned lock sha and the candidate.
export function menuCardReviewProblems(reviewed, candidate, changedPaths) {
  const problems = [];
  for (const watch of MENU_CARD_WATCH_PATHS) {
    if (!reviewed.paths.includes(watch)) {
      problems.push(`menuCardReviewed is missing watched path ${watch}.`);
    }
  }
  for (const file of reviewed.paths) {
    if (!MENU_CARD_WATCH_PATHS.includes(file) && !isWatchedMenuCardPath(file)) {
      problems.push(`menuCardReviewed lists ${file}, which is not a watched menu card path. Delete it.`);
    }
  }
  const sha = candidate.sha.toLowerCase();
  const changed = watchedMenuCardChanges(changedPaths);
  if (reviewed.digest !== candidate.digest) {
    const named = changed.length > 0 ? ` Changed: ${changed.join(", ")}.` : "";
    problems.push(
      `Watched menu card files at ${sha} do not match menuCardReviewed.digest.${named} ` +
        `Review them against meterDetail.ts and UNPORTABLE_MENU_CARD, then set menuCardReviewed.sha to ${sha}, ` +
        `menuCardReviewed.digest to ${candidate.digest}, and add each changed file to menuCardReviewed.paths.`,
    );
    return problems;
  }
  if (changed.length === 0) return problems;
  if (reviewed.sha !== sha) {
    problems.push(
      `Menu card files changed since the pinned sha: ${changed.join(", ")}. Set menuCardReviewed.sha to ${sha}.`,
    );
  }
  for (const file of changed) {
    if (!reviewed.paths.includes(file)) {
      problems.push(`menuCardReviewed.paths does not list changed file ${file}.`);
    }
  }
  return problems;
}

export function renderMeterDetail(entries) {
  const ids = Object.keys(entries).sort(compareCatalogId);
  const lines = ids.map((id) => renderProperty(id, entries[id]));
  const body =
    lines.length === 0
      ? "export const METER_DETAIL: Record<string, MeterDetail> = {};\n"
      : `export const METER_DETAIL: Record<string, MeterDetail> = {\n${lines.join("\n")}\n};\n`;
  const type = [
    'export type PrimaryDescriptionPlacement = "standard" | "reset" | "detail" | "detailLeft";',
    "",
    'export type PrimaryDetailKind = "poeBalance" | "kiroCredits";',
    "",
    "export type MeterDetail = {",
    '  primaryDescriptionPlacement?: Exclude<PrimaryDescriptionPlacement, "standard">;',
    "  showsPrimaryBalanceDescription?: true;",
    "  showsSecondaryBalanceDescription?: true;",
    "  hidesPrimaryResetWithoutDate?: true;",
    "  // The primary shows no reset text and no countdown, even when resetsAt exists.",
    "  clearsPrimaryReset?: true;",
    "  // The primary reset text is resetDescription as sent, even when a countdown exists.",
    "  usesRawPrimaryResetDescription?: true;",
    "  primaryDetailKind?: PrimaryDetailKind;",
    "  // The primary detailText becomes statusText. Upstream draws the title and that text instead of the bar.",
    "  movePrimaryDetailToStatus?: true;",
    "  secondaryDetailText?: true;",
    '  secondaryReplacesPace?: "resetDescription" | "kiroBonusCredits";',
    "  secondaryHidesResetWithoutDate?: true;",
    "  // The secondary reset text is resetDescription as sent, even when it is missing.",
    "  secondaryRawResetDescription?: true;",
    "  // A non-empty secondary resetDescription replaces the reset text.",
    "  secondaryResetDescriptionAsReset?: true;",
    "  tertiaryDetailText?: true;",
    "  // The tertiary reset text is the trimmed resetDescription, even when it is missing.",
    "  tertiaryRawResetDescription?: true;",
    "  extraResetDescriptionAsDetail?: true | string;",
    '  extraDetailLeft?: "kiroOverage";',
    "};",
    "",
  ].join("\n");
  return `${METER_DETAIL_BANNER}${type}\n${body}`;
}

export function meterDetailEntries(presentations) {
  const entries = {};
  for (const [id, presentation] of presentations) {
    const entry = meterEntryFromPresentation(id, presentation);
    if (entry) entries[id] = entry;
  }
  return entries;
}

export async function checkMeterDetailFile(root, entries) {
  const expected = renderMeterDetail(entries);
  const actual = await readFile(path.join(root, METER_DETAIL_PATH), "utf8");
  if (actual === expected) return [];
  return [`${METER_DETAIL_PATH} does not match the menu card descriptors. Run ${SYNC_METER_DETAIL_COMMAND}.`];
}

// Keep properties inside Prettier's printWidth so a generated table lints unchanged.
function renderProperty(id, entry) {
  const fields = [];
  for (const key of ENTRY_FIELDS) {
    const rendered = renderField(key, entry[key]);
    if (rendered) fields.push(rendered);
  }
  const single = `  ${id}: { ${fields.join(", ")} },`;
  if (single.length <= 120) return single;
  return `  ${id}: {\n${fields.map((field) => `    ${field},`).join("\n")}\n  },`;
}

function renderField(key, value) {
  if (value === undefined || value === false || value === "standard" || value === "none") return undefined;
  if (value === true) return `${key}: true`;
  if (typeof value === "string") return `${key}: ${JSON.stringify(value)}`;
  return undefined;
}

function compareCatalogId(left, right) {
  const order = CATALOG_PROVIDER_ORDER;
  const leftIndex = order.indexOf(left);
  const rightIndex = order.indexOf(right);
  const leftRank = leftIndex === -1 ? Number.MAX_SAFE_INTEGER : leftIndex;
  const rightRank = rightIndex === -1 ? Number.MAX_SAFE_INTEGER : rightIndex;
  if (leftRank !== rightRank) return leftRank - rightRank;
  if (left < right) return -1;
  if (left > right) return 1;
  return 0;
}

function sameEntry(expected, actual) {
  return JSON.stringify(normalizeEntry(expected)) === JSON.stringify(normalizeEntry(actual));
}

function normalizeEntry(entry) {
  if (!entry) return {};
  const normalized = {};
  for (const key of ENTRY_FIELDS) {
    const rendered = renderField(key, entry[key]);
    if (!rendered) continue;
    normalized[key] = entry[key] === true ? true : entry[key];
  }
  for (const key of Object.keys(entry)) {
    if (!ENTRY_FIELDS.includes(key) && entry[key] !== undefined) {
      normalized[key] = entry[key];
    }
  }
  return normalized;
}

function describeEntry(entry) {
  const normalized = normalizeEntry(entry);
  const parts = [];
  for (const key of Object.keys(normalized)) {
    const value = normalized[key];
    parts.push(value === true ? key : `${key} ${value}`);
  }
  return parts.length === 0 ? "no menu-card detail" : parts.join(", ");
}

function classifyExtraResetDetail(raw) {
  if (raw === undefined) return { ported: null, unportable: null };
  const trimmed = stripLeadingTrivia(raw);
  if (!trimmed.startsWith("{")) {
    throw new Error("extraRateWindowUsesResetDescriptionAsDetail is not a closure");
  }
  const normalized = normalizeClosure(trimmed);
  if (normalized === TRIVIAL_FALSE) return { ported: null, unportable: null };
  if (normalized === TRIVIAL_TRUE) return { ported: true, unportable: null };
  const idMatch = /^\{\$0\.id=="([^"]+)"\}$/.exec(normalized);
  if (idMatch) return { ported: idMatch[1], unportable: null };
  return { ported: null, unportable: trimmed };
}

function normalizeClosure(raw) {
  return raw
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/\/\/[^\n]*/g, "")
    .replace(/\s+/g, "");
}

function parseArgs(argSource) {
  const args = new Map();
  for (const part of splitTopLevel(argSource, ",")) {
    // Comments sit between arguments. A comma inside one must not split, and the
    // comment itself has to come off before the label or the next argument looks unlabeled.
    const trimmed = stripLeadingTrivia(part);
    if (!trimmed) continue;
    const match = /^([A-Za-z_][A-Za-z0-9_]*)\s*:([\s\S]*)$/.exec(trimmed);
    if (!match) {
      throw new Error(`Unlabeled menu card argument: ${trimmed.slice(0, 80)}`);
    }
    args.set(match[1], match[2].trim());
  }
  return args;
}

function stripLeadingTrivia(source) {
  let index = 0;
  while (index < source.length) {
    if (source.startsWith("//", index) || source.startsWith("/*", index)) {
      index = skipTriviaOrString(source, index);
      continue;
    }
    if (/\s/.test(source[index])) {
      index += 1;
      continue;
    }
    break;
  }
  return source.slice(index).trim();
}

function boolArg(args, name, fallback) {
  if (!args.has(name)) return fallback;
  const raw = stripTrivia(args.get(name));
  if (raw === "true") return true;
  if (raw === "false") return false;
  throw new Error(`${name} is ${raw}, not a boolean literal`);
}

function enumArg(args, name, fallback, allowed) {
  if (!args.has(name)) return fallback;
  const raw = stripTrivia(args.get(name));
  const match = /^\.([A-Za-z0-9_]+)$/.exec(raw);
  if (!match || !allowed.has(match[1])) {
    throw new Error(`${name} is ${raw}, not a supported literal`);
  }
  return match[1];
}

function unknownArgs(args, known) {
  const unknown = {};
  for (const [name, value] of args) {
    if (!Object.hasOwn(known, name)) unknown[name] = value;
  }
  return unknown;
}

// `{ _ in true }` ports as true. `{ _ in false }` is the default. Any other body stays unportable.
function classifyAlwaysClosure(args, name) {
  if (!args.has(name)) return { ported: false, unportable: null };
  const raw = stripLeadingTrivia(args.get(name));
  if (!raw.startsWith("{")) {
    throw new Error(`${name} is not a closure`);
  }
  const normalized = normalizeClosure(raw);
  if (normalized === TRIVIAL_FALSE) return { ported: false, unportable: null };
  if (normalized === TRIVIAL_TRUE) return { ported: true, unportable: null };
  return { ported: false, unportable: raw };
}

// Any value other than the default literal stays raw for UNPORTABLE_MENU_CARD.
function rawArg(args, name, trivial) {
  if (!args.has(name)) return null;
  const raw = stripTrivia(args.get(name));
  return raw.replace(/\s+/g, "") === trivial ? null : raw;
}

function compareCodePoints(left, right) {
  if (left < right) return -1;
  if (left > right) return 1;
  return 0;
}

function closureArg(args, name, trivial) {
  if (!args.has(name)) return null;
  const raw = stripLeadingTrivia(args.get(name));
  if (!raw.startsWith("{")) {
    throw new Error(`${name} is not a closure`);
  }
  const normalized = raw.replace(/\/\*[\s\S]*?\*\//g, "").replace(/\/\/[^\n]*/g, "").replace(/\s+/g, "");
  return normalized === trivial ? null : raw;
}

function stripTrivia(value) {
  return value.replace(/\/\*[\s\S]*?\*\//g, "").replace(/\/\/[^\n]*/g, "").trim();
}

function findCalls(source, name) {
  const calls = [];
  for (let index = 0; index < source.length; index += 1) {
    const skipped = skipTriviaOrString(source, index);
    if (skipped !== index) {
      index = skipped - 1;
      continue;
    }
    if (!source.startsWith(name, index)) continue;
    if (isIdentChar(source[index - 1]) || isIdentChar(source[index + name.length])) continue;
    const open = skipSpaces(source, index + name.length);
    if (source[open] !== "(") continue;
    const end = matchCloser(source, open, "(", ")");
    calls.push(source.slice(open + 1, end));
    index = end;
  }
  return calls;
}

function splitTopLevel(source, separator) {
  const parts = [];
  let start = 0;
  let paren = 0;
  let brace = 0;
  let bracket = 0;
  for (let index = 0; index < source.length; index += 1) {
    const skipped = skipTriviaOrString(source, index);
    if (skipped !== index) {
      index = skipped - 1;
      continue;
    }
    const char = source[index];
    if (char === "(") paren += 1;
    else if (char === ")") paren -= 1;
    else if (char === "{") brace += 1;
    else if (char === "}") brace -= 1;
    else if (char === "[") bracket += 1;
    else if (char === "]") bracket -= 1;
    else if (char === separator && paren === 0 && brace === 0 && bracket === 0) {
      parts.push(source.slice(start, index));
      start = index + 1;
    }
  }
  parts.push(source.slice(start));
  return parts;
}

function matchCloser(source, openIndex, open, close) {
  let depth = 0;
  for (let index = openIndex; index < source.length; index += 1) {
    const skipped = skipTriviaOrString(source, index);
    if (skipped !== index) {
      index = skipped - 1;
      continue;
    }
    if (source[index] === open) depth += 1;
    else if (source[index] === close) {
      depth -= 1;
      if (depth === 0) return index;
    }
  }
  throw new Error(`Unterminated ${open}`);
}

function skipSpaces(source, index) {
  let cursor = index;
  while (cursor < source.length) {
    const skipped = skipTriviaOrString(source, cursor);
    if (skipped !== cursor) {
      cursor = skipped;
      continue;
    }
    if (!/\s/.test(source[cursor])) return cursor;
    cursor += 1;
  }
  return cursor;
}

function skipTriviaOrString(source, index) {
  if (source.startsWith("//", index)) {
    const newline = source.indexOf("\n", index);
    return newline < 0 ? source.length : newline + 1;
  }
  if (source.startsWith("/*", index)) {
    const end = source.indexOf("*/", index + 2);
    if (end < 0) throw new Error("Unterminated comment");
    return end + 2;
  }
  if (source.startsWith('"""', index)) {
    const end = source.indexOf('"""', index + 3);
    if (end < 0) throw new Error("Unterminated string");
    return end + 3;
  }
  const quote = source[index];
  if (quote === '"' || quote === "'") return skipString(source, index);
  return index;
}

function skipString(source, index) {
  const quote = source[index];
  let cursor = index + 1;
  while (cursor < source.length) {
    if (source[cursor] === "\\") {
      cursor += 2;
      continue;
    }
    if (source[cursor] === quote) return cursor + 1;
    cursor += 1;
  }
  throw new Error("Unterminated string");
}

function isIdentChar(char) {
  return typeof char === "string" && /[A-Za-z0-9_]/.test(char);
}
